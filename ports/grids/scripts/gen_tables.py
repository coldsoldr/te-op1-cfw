#!/usr/bin/env python3
"""Generate src/grids_tables.cc from upstream Grids' resources.cc.

Copies the 25 drum-map nodes (3 parts x 32 steps each) and the Euclidean
pattern table verbatim into plain const arrays (no PROGMEM, no pointer
tables, so the data needs no relocation in a freestanding OP-1 image).
The tempo table is not used: the OP-1 sequencer clock replaces it.

usage: gen_tables.py MI_DIR OUT_CC [--stats]
"""
import re
import sys


def parse_arrays(text):
    arrays = {}
    for m in re.finditer(r'const prog_uint(8|32)_t (\w+)\[\] PROGMEM = \{(.*?)\};', text, re.S):
        bits, name, body = m.group(1), m.group(2), m.group(3)
        body = re.sub(r'//.*', '', body)
        vals = [int(v, 0) for v in re.findall(r'(0x[0-9a-fA-F]+|\d+)', body)]
        arrays[name] = (int(bits), vals)
    return arrays


def main():
    mi, out = sys.argv[1], sys.argv[2]
    text = open(mi + '/grids/resources.cc').read()
    arrays = parse_arrays(text)
    nodes = [arrays['node_%d' % i][1] for i in range(25)]
    for i, n in enumerate(nodes):
        assert len(n) == 96, (i, len(n))
        assert all(0 <= v <= 255 for v in n)
    euclid = arrays['lut_res_euclidean'][1]
    assert len(euclid) == 1024, len(euclid)

    if '--stats' in sys.argv:
        odd = sum(1 for n in nodes for s in range(96) if s % 2 and n[s])
        print('non-zero odd (32nd-note) steps across all nodes:', odd)

    o = []
    o.append('// Generated by scripts/gen_tables.py from upstream Grids resources.cc.')
    o.append('// Grids is (c) 2011-2012 Emilie Gillet, GPL v3. Do not edit.')
    o.append('')
    o.append('#include "src/grids_tables.h"')
    o.append('')
    o.append('namespace op1grids {')
    o.append('')
    o.append('// node_0 .. node_24; each: BD steps 0..31, SD steps 0..31, HH steps 0..31.')
    o.append('const uint8_t kDrumNodes[kNumNodes][kNodeSize] = {')
    for i, n in enumerate(nodes):
        o.append('  {  // node_%d' % i)
        for r in range(0, 96, 16):
            o.append('    ' + ' '.join('%3d,' % v for v in n[r:r + 16]))
        o.append('  },')
    o.append('};')
    o.append('')
    o.append('// lut_res_euclidean: index (length - 1) * 32 + (density >> 3); bit k = step k.')
    o.append('const uint32_t kEuclidean[1024] = {')
    for r in range(0, 1024, 6):
        o.append('  ' + ' '.join('0x%08x,' % v for v in euclid[r:r + 6]))
    o.append('};')
    o.append('')
    o.append('}  // namespace op1grids')
    o.append('')
    open(out, 'w', newline='\n').write('\n'.join(o))
    print('wrote', out)


if __name__ == '__main__':
    main()
