# Tables for the port's digital VCF (src/core/core_tables.cc): the
# zero-delay-feedback state-variable filter in Andrew Simper's form,
#   g = tan(pi fc / fs), a1 = 1 / (1 + g (g + k)), a2 = g a1, a3 = g a2,
# all three in [0, 1), stored Q31 for 257 cutoff codes (frequency >> 8), for
# each damping k. The cutoff map (src/core/core_config.h, mirrored here):
#   fc = 20 Hz * 2^(10 * code / 65536), capped at 0.45 fs.
#
#   python3 resources/gen_core_tables.py src/core/core_tables.cc

import math
import sys

FS = 44100.0
MIN_HZ = 20.0
OCTAVES = 10.0
MAX_RATIO = 0.45
DAMPINGS = [('kDampingFlat', math.sqrt(2.0)), ('kDampingResonant', 0.5)]


def cutoff(code):
    fc = MIN_HZ * 2.0 ** (OCTAVES * code / 65536.0)
    return min(fc, MAX_RATIO * FS)


def q31(x):
    v = int(round(x * 2147483648.0))
    return min(v, 2147483647)


def coefficients(code, k):
    g = math.tan(math.pi * cutoff(code) / FS)
    a1 = 1.0 / (1.0 + g * (g + k))
    a2 = g * a1
    a3 = g * a2
    return q31(a1), q31(a2), q31(a3)


def main(argv):
    path = argv[1]
    out = ['// Generated by resources/gen_core_tables.py: SVF coefficients (Simper\'s',
           '// a1, a2, a3, Q31) for cutoff codes 0, 256, ..., 65536, per damping.',
           '',
           '#include "src/core/core_tables.h"',
           '',
           'namespace op1streams {',
           '',
           'const int32_t kSvfTable[kNumDampings][257][3] = {']
    for name, k in DAMPINGS:
        out.append('  {  // %s, k = %.6f' % (name, k))
        for i in range(257):
            a1, a2, a3 = coefficients(i * 256, k)
            out.append('    { %10d, %10d, %10d },' % (a1, a2, a3))
        out.append('  },')
    out.append('};')
    out.append('')
    out.append('}  // namespace op1streams')
    open(path, 'w', newline='\n').write('\n'.join(out) + '\n')
    print('wrote', path)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
