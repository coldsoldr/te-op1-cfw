#!/usr/bin/env python3
"""Generates src/halfband_taps.h: the half-band interpolation FIR of the 4x
upsampler (op1/engine.cc, OP1RINGS_UPSAMPLE 4: 22.05 -> 44.1 kHz, then the
2x Lagrange stage to 88.2 kHz).

A half-band low-pass of N = 4 L' - 1 = 47 taps (L = 23 each side): the centre
tap is 1/2, every other even tap is 0, so interpolating by 2 costs only the
odd taps: the even output samples are the input delayed by 12, the odd ones
are sum_j c_j (x[m - j] + x[m + 1 + j]) over j = 0..11, c_j = 2 h[2 j + 1].
Kaiser window, A = 60 dB. Coefficients in Q14 (sum c_j = 1/2 exactly), so a
16-bit-scaled input never overflows the 32-bit accumulator.

Pure Python (no numpy): run it once, commit the header.
"""
import math
import os

N_SIDE = 23          # taps each side of the centre (odd ones carry the signal)
A_DB = 60.0          # Kaiser stop-band attenuation
Q = 14
RATE = 44100.0       # the output rate of this stage


def i0(x):
    """Modified Bessel function of the first kind, order 0 (series)."""
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2.0 * k)) ** 2
        s += term
        k += 1
    return s


def kaiser(n, length, beta):
    r = 2.0 * n / (length - 1) - 1.0
    return i0(beta * math.sqrt(max(0.0, 1.0 - r * r))) / i0(beta)


def design():
    beta = 0.1102 * (A_DB - 8.7)
    length = 2 * N_SIDE + 1
    taps = []
    for n in range(-N_SIDE, N_SIDE + 1):
        ideal = 0.5 if n == 0 else math.sin(math.pi * n / 2.0) / (math.pi * n)
        taps.append(ideal * kaiser(n + N_SIDE, length, beta))
    c = [2.0 * taps[N_SIDE + 2 * j + 1] for j in range((N_SIDE + 1) // 2)]
    scale = 0.5 / sum(c)                      # unity DC gain
    c = [v * scale for v in c]
    q = [int(round(v * (1 << Q))) for v in c]
    q[0] += (1 << (Q - 1)) - sum(q)           # sum c_j = 1/2 exactly in Q14
    return c, q


def response_db(q, hz):
    """Magnitude of the full interpolation filter (2x gain, even + odd phases)
    at hz, output rate RATE."""
    w = 2.0 * math.pi * hz / RATE
    re = 1.0                                  # the centre tap (2 x 1/2)
    for j, v in enumerate(q):
        re += 2.0 * (v / float(1 << Q)) * math.cos(w * (2 * j + 1))
    return 20.0 * math.log10(max(abs(re), 1e-12)) - 20.0 * math.log10(2.0)


def main():
    c, q = design()
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'src', 'halfband_taps.h')
    lines = ['// Generated by resources/gen_halfband.py. Do not edit.',
             '//',
             '// Half-band interpolation taps (odd phase), Q%d: %d taps each side of the' % (Q, N_SIDE),
             '// centre, Kaiser %.0f dB. Response of the 22.05 -> 44.1 kHz stage:' % A_DB]
    for hz in (5000, 8000, 9000, 9500, 10000, 11025, 12000, 12500, 13000, 15000, 20000):
        lines.append('//   %5d Hz: %7.2f dB' % (hz, response_db(q, hz)))
    lines += ['',
              '#ifndef OP1RINGS_HALFBAND_TAPS_H_',
              '#define OP1RINGS_HALFBAND_TAPS_H_',
              '',
              '#include <cstdint>',
              '',
              'namespace op1rings {',
              '',
              'const int32_t kHalfbandTapsQ14 = %d;' % Q,
              'const int32_t kHalfbandNumTaps = %d;   // c_j, j = 0..%d' % (len(q), len(q) - 1),
              'const int32_t kHalfbandDelay = %d;     // input samples (the even phase)' % ((len(q) * 2) // 2),
              'const int32_t kHalfbandTaps[%d] = {' % len(q)]
    lines.append('  ' + ', '.join(str(v) for v in q) + ',')
    lines += ['};', '', '}  // namespace op1rings', '', '#endif  // OP1RINGS_HALFBAND_TAPS_H_', '']
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines))
    print('\n'.join(lines[:16]))
    print('sum q =', sum(q), 'max |c| =', max(abs(v) for v in c))


if __name__ == '__main__':
    main()
