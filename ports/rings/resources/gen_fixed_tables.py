"""Generates src/fixed_tables.{h,cc}: lookup tables for the fixed-point
coefficient code (stdlib only).

  python resources/gen_fixed_tables.py   (from ports/rings)

Tables are sampled at N + 1 points, so linear interpolation can read
table[i + 1] at the last index. Values are int32 fixed point; the Q format
is in each table's name.
"""
import math
import os

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')

# stmlib's FREQUENCY_FAST tan approximation (filter.h), which upstream uses
# for the resonator's partials. Built into the sin/cos tables, so the port
# tunes the partials exactly like upstream, including its flattening near
# Nyquist (tan_fast(0.49) = 4.3, not tan(0.49 pi) = 31.8).
A = 3.260e-01 * math.pi ** 3
B = 1.823e-01 * math.pi ** 5


def tan_fast(f):
    f2 = f * f
    return f * (math.pi + f2 * (A + B * f2))


def q(v, bits):
    x = int(math.floor(v * (1 << bits) + 0.5))
    return max(-(1 << 31), min((1 << 31) - 1, x))


tables = []  # (name, comment, values)

# Partial frequency pf in [0, 0.5] -> phi = atan(tan_fast(pf)).
N_PF = 1024
pf = [0.5 * i / N_PF for i in range(N_PF + 1)]
phi = [math.atan(tan_fast(x)) for x in pf]
tables.append(('kSinPhiQ31', 'sin(phi(pf)), pf = 0.5 i / %d' % N_PF, [q(math.sin(p), 31) for p in phi]))
tables.append(('kCosPhiQ31', 'cos(phi(pf))', [q(math.cos(p), 31) for p in phi]))
tables.append(('kSecPhiQ28', '1 / cos(phi(pf)) (<= 4.4)', [q(1.0 / math.cos(p), 28) for p in phi]))
tables.append(('kTanPhiQ28', 'tan(phi(pf)) = tan_fast(pf) (<= 4.3)', [q(math.tan(p), 28) for p in phi]))

N = 256
# log2(1 + x), x in [0, 1]: mantissa log for normalised values.
tables.append(('kLog2MantissaQ30', 'log2(1 + i / %d)' % N, [q(math.log2(1 + i / N), 30) for i in range(N + 1)]))
# 2^-x, x in [0, 1].
tables.append(('kExp2NegQ31', '2^-(i / %d)' % N, [q(2 ** -(i / N), 31) for i in range(N + 1)]))
# 1 / (1 + t), t in [0, 1].
tables.append(('kRecip1pQ31', '1 / (1 + i / %d)' % N, [q(1 / (1 + i / N), 31) for i in range(N + 1)]))
# rho(x) = (1 + x)^-1/2, x in [0, 0.5].
tables.append(('kRhoQ31', '(1 + 0.5 i / %d)^-1/2' % N, [q((1 + 0.5 * i / N) ** -0.5, 31) for i in range(N + 1)]))
# 1 / rho(x) = sqrt(1 + x), x in [0, 0.5].
tables.append(('kInvRhoQ30', 'sqrt(1 + 0.5 i / %d)' % N, [q((1 + 0.5 * i / N) ** 0.5, 30) for i in range(N + 1)]))
# 1 / (1 - x), x in [0, 0.5].
tables.append(('kRecip1mQ30', '1 / (1 - 0.5 i / %d)' % N, [q(1 / (1 - 0.5 * i / N), 30) for i in range(N + 1)]))

# stmlib::SoftLimit(x) = x (27 + x^2) / (27 + 9 x^2), x in [0, 4] (odd).
def soft_limit(x):
    return x * (27 + x * x) / (27 + 9 * x * x)
tables.append(('kSoftLimitQ30', 'SoftLimit(4 i / %d)' % N, [q(soft_limit(4.0 * i / N), 30) for i in range(N + 1)]))

# Rings' stiffness table (rings/resources/lookup_tables.py), Q28.
stiffness = []
for i in range(257):
    g = i / 256.0
    if g < 0.25:
        s = -(0.25 - g) * 0.25
    elif g < 0.3:
        s = 0.0
    elif g < 0.9:
        s = 0.01 * 10 ** ((g - 0.3) / 0.6 * 2.005) - 0.01
    else:
        gg = ((g - 0.9) / 0.1) ** 2
        s = 1.5 - math.cos(gg * math.pi) / 2.0
    stiffness.append(s)
stiffness[-1] = 2.0
stiffness[-2] = 2.0
tables.append(('kStiffnessQ28', "Rings' lut_stiffness", [q(s, 28) for s in stiffness]))

# FM voice: one sine cycle over 4096 entries (upstream reads lut_sine with
# phase >> 20), Q31 (+1 is clamped).
N_SINE = 4096
tables.append(('kSineQ31', 'sin(2 pi i / %d)' % N_SINE,
               [q(math.sin(2 * math.pi * i / N_SINE), 31) for i in range(N_SINE + 1)]))

# Rings' FM ratio quantizer (rings/resources/lookup_tables.py), in
# semitones, Q24.
fm_frequency_ratios = [
    0.5, 0.5 * 2 ** (16 / 1200.0), math.sqrt(2) / 2, math.pi / 4, 1.0,
    1.0 * 2 ** (16 / 1200.0), math.sqrt(2), math.pi / 2, 7.0 / 4, 2,
    2 * 2 ** (16 / 1200.0), 9.0 / 4, 11.0 / 4, 2 * math.sqrt(2), 3, math.pi,
    math.sqrt(3) * 2, 4, math.sqrt(2) * 3, math.pi * 3 / 2, 5,
    math.sqrt(2) * 4, 8]
scale = []
for ratio in fm_frequency_ratios:
    scale.extend([12 * math.log2(ratio)] * 3)
target_size = 1 << math.ceil(math.log2(len(scale)))
while len(scale) < target_size:
    diffs = [b - a for a, b in zip(scale, scale[1:])]
    gap = diffs.index(max(diffs))   # numpy.argmax: the first maximum
    scale = scale[:gap + 1] + [(scale[gap] + scale[gap + 1]) / 2] + scale[gap + 1:]
scale.append(scale[-1])
tables.append(('kFmRatioSemitonesQ24', "Rings' lut_fm_frequency_quantizer (semitones)",
               [q(s, 24) for s in scale]))

header = ['// Generated by resources/gen_fixed_tables.py. Do not edit.',
          '',
          '#ifndef OP1RINGS_FIXED_TABLES_H_',
          '#define OP1RINGS_FIXED_TABLES_H_',
          '',
          '#include <cstdint>',
          '',
          'namespace op1rings {',
          '',
          'const int32_t kPfTableBits = 10;  // pf tables: %d + 1 entries over [0, 0.5]' % N_PF,
          'const int32_t kTableBits = 8;     // other tables: %d + 1 entries' % N,
          '']
source = ['// Generated by resources/gen_fixed_tables.py. Do not edit.',
          '',
          '#include "src/fixed_tables.h"',
          '',
          'namespace op1rings {',
          '']
for name, comment, values in tables:
    header.append('extern const int32_t %s[%d];  // %s' % (name, len(values), comment))
    source.append('const int32_t %s[%d] = {' % (name, len(values)))
    for i in range(0, len(values), 6):
        source.append('  ' + ', '.join('%d' % v for v in values[i:i + 6]) + ',')
    source.append('};')
    source.append('')
header += ['', '}  // namespace op1rings', '', '#endif  // OP1RINGS_FIXED_TABLES_H_', '']
source += ['}  // namespace op1rings', '']

with open(os.path.join(OUT_DIR, 'fixed_tables.h'), 'w', newline='\n') as f:
    f.write('\n'.join(header))
with open(os.path.join(OUT_DIR, 'fixed_tables.cc'), 'w', newline='\n') as f:
    f.write('\n'.join(source))
print('wrote %d tables' % len(tables))
