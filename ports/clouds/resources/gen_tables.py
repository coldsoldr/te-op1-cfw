"""Generates src/core/clouds_tables.{h,cc}: Clouds' lookup tables in fixed
point (stdlib only).

  python3 resources/gen_tables.py   (from ports/clouds; needs
                                     ../../mutableinstruments)

The values are parsed from upstream's float tables (clouds/resources.cc,
stmlib/dsp/units.cc), so the port uses exactly upstream's numbers, then
quantised. Tables read by linear interpolation carry one extra entry
(a copy of the last), where upstream reads one past its end with a zero
fraction.
"""
import math
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
MI = os.path.join(HERE, '..', '..', '..', 'mutableinstruments')
OUT_DIR = os.path.join(HERE, '..', 'src', 'core')


def parse_float_table(path, name):
    text = open(path).read()
    m = re.search(r'const float %s\[\] = \{(.*?)\};' % re.escape(name), text, re.S)
    if not m:
        raise ValueError('%s not found in %s' % (name, path))
    return [float(v) for v in m.group(1).replace('\n', ' ').split(',') if v.strip()]


def q(v, bits):
    x = int(math.floor(v * (1 << bits) + 0.5))
    return max(-(1 << 31), min((1 << 31) - 1, x))


resources = os.path.join(MI, 'clouds', 'resources.cc')
units = os.path.join(MI, 'stmlib', 'dsp', 'units.cc')

tables = []  # (ctype, name, comment, values)

grain = parse_float_table(resources, 'lut_grain_size')
assert len(grain) == 257
tables.append(('int32_t', 'kGrainSize', "lut_grain_size (samples at 32 kHz), + 1 guard", [int(v) for v in grain] + [int(grain[-1])]))

window = parse_float_table(resources, 'lut_window')
assert len(window) == 4097
tables.append(('int32_t', 'kWindowQ30', 'lut_window (grain window), Q30, + 1 guard', [q(v, 30) for v in window] + [q(window[-1], 30)]))

xin = parse_float_table(resources, 'lut_xfade_in')
xout = parse_float_table(resources, 'lut_xfade_out')
assert len(xin) == 17 and len(xout) == 17
tables.append(('int32_t', 'kXfadeInQ31', 'lut_xfade_in, Q31, + 1 guard', [q(v, 31) for v in xin] + [q(xin[-1], 31)]))
tables.append(('int32_t', 'kXfadeOutQ31', 'lut_xfade_out, Q31, + 1 guard', [q(v, 31) for v in xout] + [q(xout[-1], 31)]))

sin = parse_float_table(resources, 'lut_sin')
tables.append(('int32_t', 'kSinQ31', 'lut_sin[0..513] (sin(2 pi i / 1024)), Q31: mono grain pan', [q(v, 31) for v in sin[:514]]))

high = parse_float_table(units, 'lut_pitch_ratio_high')
low = parse_float_table(units, 'lut_pitch_ratio_low')
assert len(high) == 256 and len(low) == 256
# High table as FFloat parts: value = m * 2^e, |m| in [2^30, 2^31).
hm, he = [], []
for v in high:
    e = math.floor(math.log2(v)) - 30
    m = int(math.floor(v / 2.0 ** e + 0.5))
    if m >= 1 << 31:
        m >>= 1
        e += 1
    hm.append(m)
    he.append(e)
tables.append(('int32_t', 'kPitchRatioHighM', 'lut_pitch_ratio_high: FFloat mantissas', hm))
tables.append(('int32_t', 'kPitchRatioHighE', 'lut_pitch_ratio_high: FFloat exponents', he))
tables.append(('int32_t', 'kPitchRatioLowQ30', 'lut_pitch_ratio_low, Q30', [q(v, 30) for v in low]))


def emit():
    h = ['// Generated by resources/gen_tables.py. Do not edit.', '',
         '#ifndef OP1CLOUDS_CORE_CLOUDS_TABLES_H_', '#define OP1CLOUDS_CORE_CLOUDS_TABLES_H_', '',
         '#include <cstdint>', '', 'namespace op1clouds {', '']
    c = ['// Generated by resources/gen_tables.py. Do not edit.', '',
         '#include "src/core/clouds_tables.h"', '', 'namespace op1clouds {', '']
    for ctype, name, comment, values in tables:
        h.append('extern const %s %s[%d];  // %s' % (ctype, name, len(values), comment))
        c.append('const %s %s[%d] = {' % (ctype, name, len(values)))
        for i in range(0, len(values), 8):
            c.append('  ' + ', '.join(str(v) for v in values[i:i + 8]) + ',')
        c.append('};')
        c.append('')
    h += ['', '}  // namespace op1clouds', '', '#endif  // OP1CLOUDS_CORE_CLOUDS_TABLES_H_', '']
    c += ['}  // namespace op1clouds', '']
    open(os.path.join(OUT_DIR, 'clouds_tables.h'), 'w').write('\n'.join(h))
    open(os.path.join(OUT_DIR, 'clouds_tables.cc'), 'w').write('\n'.join(c))


if __name__ == '__main__':
    emit()
