// Generates fixed/tables.{h,cc}: upstream Plaits' float lookup tables in
// fixed point (rounded from the exact float values, so the port interpolates
// the same tables as upstream), plus pitch and reciprocal tables.
//
//   make tables   (builds this on the host against upstream's resources.cc)

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <string>

#include "plaits/resources.h"
#include "stmlib/dsp/units.h"
// The speech engine's tables are private static members upstream.
#define private public
#include "plaits/dsp/speech/lpc_speech_synth_controller.h"
#include "plaits/dsp/speech/lpc_speech_synth_words.h"
#include "plaits/dsp/speech/naive_speech_synth.h"
#include "plaits/dsp/speech/sam_speech_synth.h"
#undef private

namespace {

FILE* h;
FILE* c;

int32_t Round(double v, int bits) {
  double s = std::floor(v * std::ldexp(1.0, bits) + 0.5);
  if (s > 2147483647.0) s = 2147483647.0;
  if (s < -2147483648.0) s = -2147483648.0;
  return static_cast<int32_t>(s);
}

void Table(const char* name, const char* comment, int bits, const float* v, int n) {
  fprintf(h, "// %s (Q%d)\nextern const int32_t %s[%d];\n", comment, bits, name, n);
  fprintf(c, "const int32_t %s[%d] = {", name, n);
  for (int i = 0; i < n; ++i) {
    fprintf(c, "%s%d,", (i % 8) ? " " : "\n  ", Round(v[i], bits));
  }
  fprintf(c, "\n};\n\n");
}

void TableI16(const char* name, const char* comment, const int16_t* v, int n) {
  fprintf(h, "// %s (int16, as upstream)\nextern const int16_t %s[%d];\n", comment, name, n);
  fprintf(c, "const int16_t %s[%d] = {", name, n);
  for (int i = 0; i < n; ++i) {
    fprintf(c, "%s%d,", (i % 12) ? " " : "\n  ", v[i]);
  }
  fprintf(c, "\n};\n\n");
}

void TableD(const char* name, const char* comment, int bits, const double* v, int n,
            const char* type = "int32_t") {
  fprintf(h, "// %s (Q%d)\nextern const %s %s[%d];\n", comment, bits, type, name, n);
  fprintf(c, "const %s %s[%d] = {", type, name, n);
  for (int i = 0; i < n; ++i) {
    double s = std::floor(v[i] * std::ldexp(1.0, bits) + 0.5);
    if (std::string(type) == "uint32_t") {
      if (s > 4294967295.0) s = 4294967295.0;
      fprintf(c, "%s%lluu,", (i % 6) ? " " : "\n  ", static_cast<unsigned long long>(s));
    } else {
      fprintf(c, "%s%d,", (i % 8) ? " " : "\n  ", Round(v[i], bits));
    }
  }
  fprintf(c, "\n};\n\n");
}

}  // namespace

int main(int argc, char** argv) {
  if (argc < 3) {
    fprintf(stderr, "usage: %s tables.h tables.cc\n", argv[0]);
    return 1;
  }
  h = fopen(argv[1], "w");
  c = fopen(argv[2], "w");
  fprintf(h, "// Generated by resources/gen_tables.cc: do not edit.\n\n"
             "#ifndef OP1PLAITS_FIXED_TABLES_H_\n#define OP1PLAITS_FIXED_TABLES_H_\n\n"
             "#include <cstdint>\n\nnamespace op1plaits {\n\n");
  fprintf(c, "// Generated by resources/gen_tables.cc: do not edit.\n\n"
             "#include \"fixed/tables.h\"\n\nnamespace op1plaits {\n\n");

  {
    // Sine: kept 2^11 LSB inside +-2^31, so the 16-bit interpolation in
    // Sine() (fixed_math.h), which can overshoot an entry by a few LSB of its
    // Q21 difference, never wraps around at the peaks (a 1e-6 change).
    float v[LUT_SINE_SIZE];
    const float limit = 1.0f - 2048.0f / 2147483648.0f;
    for (int i = 0; i < LUT_SINE_SIZE; ++i) {
      float s = plaits::lut_sine[i];
      v[i] = s > limit ? limit : (s < -limit ? -limit : s);
    }
    Table("lut_sine_q31", "upstream lut_sine, peaks at +-(1 - 2^-20)", 31, v, LUT_SINE_SIZE);
  }
  Table("lut_fm_frequency_quantizer_q16", "upstream lut_fm_frequency_quantizer, semitones", 16,
        plaits::lut_fm_frequency_quantizer, LUT_FM_FREQUENCY_QUANTIZER_SIZE);
  Table("lut_fold_q30", "upstream lut_fold", 30, plaits::lut_fold, LUT_FOLD_SIZE);
  Table("lut_fold_2_q30", "upstream lut_fold_2", 30, plaits::lut_fold_2, LUT_FOLD_2_SIZE);
  Table("lut_stiffness_q29", "upstream lut_stiffness", 29, plaits::lut_stiffness, LUT_STIFFNESS_SIZE);
  Table("lut_svf_shift_q31", "upstream lut_svf_shift", 31, plaits::lut_svf_shift, LUT_SVF_SHIFT_SIZE);
  Table("lut_4x_downsampler_fir_q31", "upstream lut_4x_downsampler_fir", 31,
        plaits::lut_4x_downsampler_fir, LUT_4X_DOWNSAMPLER_FIR_SIZE);

  TableI16("lut_ws_inverse_tan", "upstream lut_ws_inverse_tan", plaits::lut_ws_inverse_tan,
           LUT_WS_INVERSE_TAN_SIZE);
  TableI16("lut_ws_inverse_sin", "upstream lut_ws_inverse_sin", plaits::lut_ws_inverse_sin,
           LUT_WS_INVERSE_SIN_SIZE);
  TableI16("lut_ws_linear", "upstream lut_ws_linear", plaits::lut_ws_linear, LUT_WS_LINEAR_SIZE);
  TableI16("lut_ws_bump", "upstream lut_ws_bump", plaits::lut_ws_bump, LUT_WS_BUMP_SIZE);
  TableI16("lut_ws_double_bump", "upstream lut_ws_double_bump", plaits::lut_ws_double_bump,
           LUT_WS_DOUBLE_BUMP_SIZE);

  TableI16("wav_integrated_waves", "upstream wav_integrated_waves (192 x 132)",
           plaits::wav_integrated_waves, WAV_INTEGRATED_WAVES_SIZE);
  {
    // WavetableEngine::LoadUserData without user data: wave index per
    // (bank, x, y); bank 3 is waves w * 101 % 192.
    fprintf(h, "// the wavetable engine's wave map (bank * 64 + y * 8 + x -> wave)\n"
               "extern const uint8_t wavetable_wave_map[256];\n");
    fprintf(c, "const uint8_t wavetable_wave_map[256] = {");
    for (int i = 0; i < 256; ++i) {
      int w = i >= 192 ? (i * 101 % 192) : i;
      fprintf(c, "%s%d,", (i % 16) ? " " : "\n  ", w);
    }
    fprintf(c, "\n};\n\n");
  }

  {
    // ChordBank::Reset(): the chords' ratios (SemitonesToRatio, float, as
    // upstream computes them) and note counts. The chord table is upstream's
    // (chord_bank.cc, without JON_CHORDS).
    static const float chords[11][4] = {
      { 0.00f, 0.01f, 11.99f, 12.00f }, { 0.00f, 7.00f, 7.01f, 12.00f },
      { 0.00f, 5.00f, 7.00f, 12.00f }, { 0.00f, 3.00f, 7.00f, 12.00f },
      { 0.00f, 3.00f, 7.00f, 10.00f }, { 0.00f, 3.00f, 10.00f, 14.00f },
      { 0.00f, 3.00f, 10.00f, 17.00f }, { 0.00f, 2.00f, 9.00f, 16.00f },
      { 0.00f, 4.00f, 11.00f, 14.00f }, { 0.00f, 4.00f, 7.00f, 11.00f },
      { 0.00f, 4.00f, 7.00f, 12.00f },
    };
    float ratios[44];
    for (int i = 0; i < 11; ++i) {
      for (int j = 0; j < 4; ++j) {
        ratios[i * 4 + j] = stmlib::SemitonesToRatio(chords[i][j]);
      }
    }
    Table("chord_ratios_q28", "ChordBank ratios [chord * 4 + note]", 28, ratios, 44);
  }

  // stmlib's SemitonesToRatio tables as (mantissa, exponent) pairs, for
  // FFloat: high[i] = 2^((i - 128) / 12), low[j] = 2^(j / 3072), both
  // rounded from upstream's float values.
  {
    fprintf(h, "// stmlib lut_pitch_ratio_high / _low as FFloat parts (mantissa\n"
               "// normalised to [2^30, 2^31), value = m * 2^e)\n");
    fprintf(h, "extern const int32_t lut_pitch_ratio_high_m[257];\n"
               "extern const int8_t lut_pitch_ratio_high_e[257];\n"
               "// lut_pitch_ratio_low - 1 (Q31)\n"
               "extern const int32_t lut_pitch_ratio_low_q31[257];\n");
    fprintf(c, "const int32_t lut_pitch_ratio_high_m[257] = {");
    std::string exps;
    for (int i = 0; i < 257; ++i) {
      int e;
      double m = std::frexp(static_cast<double>(stmlib::lut_pitch_ratio_high[i]), &e);
      // m in [0.5, 1): mantissa = m * 2^31, exponent e - 31.
      int32_t mm = Round(m, 31);
      if (mm < 0) { mm = 1073741824; ++e; }
      fprintf(c, "%s%d,", (i % 8) ? " " : "\n  ", mm);
      char buf[16];
      snprintf(buf, sizeof(buf), "%s%d,", (i % 16) ? " " : "\n  ", e - 31);
      exps += buf;
    }
    fprintf(c, "\n};\n\nconst int8_t lut_pitch_ratio_high_e[257] = {%s\n};\n\n", exps.c_str());
    // low[j] in [1, 1.06): stored as (low - 1) in Q31.
    fprintf(c, "const int32_t lut_pitch_ratio_low_q31[257] = {");
    for (int i = 0; i < 257; ++i) {
      fprintf(c, "%s%d,", (i % 8) ? " " : "\n  ",
              Round(static_cast<double>(stmlib::lut_pitch_ratio_low[i]) - 1.0, 31));
    }
    fprintf(c, "\n};\n\n");
  }

  // NoteToFrequency's coarse table: a0 / 4 * 2^((i - 128) / 12) as a Q32
  // phase increment, for both sample rates (a0 = 55 Hz / fs; upstream uses
  // the corrected rate 47872.34 Hz).
  {
    const double rates[2] = { 47872.34f, 44100.0 };
    const char* names[2] = { "lut_note_frequency_48k_q32", "lut_note_frequency_44k_q32" };
    for (int r = 0; r < 2; ++r) {
      double v[257];
      const float a0 = static_cast<float>((440.0 / 8.0) / rates[r]);
      for (int i = 0; i < 257; ++i) {
        v[i] = static_cast<double>(a0 * 0.25f) * static_cast<double>(stmlib::lut_pitch_ratio_high[i]);
        if (v[i] >= 0.999999) v[i] = 0.999999;
      }
      TableD(names[r], "a0 / 4 * pitch_ratio_high[i], Q32 phase increment", 32, v, 257, "uint32_t");
    }
  }

  // The speech engine's data: LPC word banks (bytes, as upstream), the LPC
  // phoneme frames, the naive and SAM synths' formant tables.
  {
    // The word banks, decoded here by upstream's LPCSpeechSynthWordBank
    // (bit stream -> 14-byte frames) instead of at run time: upstream
    // decodes a whole bank in one block when HARMONICS selects it (~140k
    // Blackfin cycles, i.e. most of an OP-1 callback for one voice), into
    // a 14 KB buffer per voice. Decoded, the five banks are shared by every
    // voice from flash/SDRAM.
    static char ram[32768];
    stmlib::BufferAllocator allocator(ram, sizeof(ram));
    plaits::LPCSpeechSynthWordBank bank;
    bank.Init(plaits::word_banks_, LPC_SPEECH_SYNTH_NUM_WORD_BANKS, &allocator);
    int offsets[LPC_SPEECH_SYNTH_NUM_WORD_BANKS + 1];
    int num_words[LPC_SPEECH_SYNTH_NUM_WORD_BANKS];
    std::string frames, boundaries;
    int total = 0;
    for (int b = 0; b < LPC_SPEECH_SYNTH_NUM_WORD_BANKS; ++b) {
      bank.Load(b);
      offsets[b] = total;
      num_words[b] = bank.num_words_;
      char line[160];
      for (int i = 0; i < bank.num_frames_; ++i) {
        const plaits::LPCSpeechSynth::Frame& f = bank.frames_[i];
        snprintf(line, sizeof(line), "  { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d },\n",
                 f.energy, f.period, f.k0, f.k1, f.k2, f.k3, f.k4, f.k5, f.k6, f.k7, f.k8, f.k9);
        frames += line;
      }
      total += bank.num_frames_;
      boundaries += "  {";
      for (int w = 0; w <= plaits::kLPCSpeechSynthMaxWords; ++w) {
        snprintf(line, sizeof(line), " %d,", w <= bank.num_words_ ? bank.word_boundaries_[w] : 0);
        boundaries += line;
      }
      boundaries += " },\n";
    }
    offsets[LPC_SPEECH_SYNTH_NUM_WORD_BANKS] = total;
    fprintf(h, "// LPCSpeechSynth::Frame (14 bytes)\n"
               "struct LPCFrame {\n"
               "  uint8_t energy;\n  uint8_t period;\n  int16_t k0;\n  int16_t k1;\n"
               "  int8_t k2, k3, k4, k5, k6, k7, k8, k9;\n};\n");
    fprintf(h, "// The 5 LPC word banks, decoded: frames, then per bank the first frame,\n"
               "// frame count, word count and word boundaries (frame index of each word,\n"
               "// num_words + 1 entries)\n");
    fprintf(h, "extern const LPCFrame lpc_word_bank_frames[%d];\n", total);
    fprintf(c, "const LPCFrame lpc_word_bank_frames[%d] = {\n%s};\n\n", total, frames.c_str());
    fprintf(h, "struct LPCWordBankFixed { int first_frame; int num_frames; int num_words; };\n"
               "extern const LPCWordBankFixed lpc_word_banks[%d];\n", LPC_SPEECH_SYNTH_NUM_WORD_BANKS);
    fprintf(c, "const LPCWordBankFixed lpc_word_banks[%d] = {\n", LPC_SPEECH_SYNTH_NUM_WORD_BANKS);
    for (int b = 0; b < LPC_SPEECH_SYNTH_NUM_WORD_BANKS; ++b) {
      fprintf(c, "  { %d, %d, %d },\n", offsets[b], offsets[b + 1] - offsets[b], num_words[b]);
    }
    fprintf(c, "};\n\n");
    fprintf(h, "extern const int16_t lpc_word_bank_boundaries[%d][%d];\n",
            LPC_SPEECH_SYNTH_NUM_WORD_BANKS, plaits::kLPCSpeechSynthMaxWords + 1);
    fprintf(c, "const int16_t lpc_word_bank_boundaries[%d][%d] = {\n%s};\n\n",
            LPC_SPEECH_SYNTH_NUM_WORD_BANKS, plaits::kLPCSpeechSynthMaxWords + 1, boundaries.c_str());

    // LPC phoneme frames (5 vowels, 10 consonants), plus a copy of the first
    // one: the consonants are played with frame + 1 read but unused.
    fprintf(h, "// LPCSpeechSynthController::phonemes_, then phonemes_[0] again\n"
               "extern const LPCFrame lpc_phoneme_frames[%d];\n", plaits::kLPCSpeechSynthNumPhonemes + 1);
    fprintf(c, "const LPCFrame lpc_phoneme_frames[%d] = {\n", plaits::kLPCSpeechSynthNumPhonemes + 1);
    for (int i = 0; i <= plaits::kLPCSpeechSynthNumPhonemes; ++i) {
      const plaits::LPCSpeechSynth::Frame& f =
          plaits::LPCSpeechSynthController::phonemes_[i % plaits::kLPCSpeechSynthNumPhonemes];
      fprintf(c, "  { %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d },\n", f.energy, f.period,
              f.k0, f.k1, f.k2, f.k3, f.k4, f.k5, f.k6, f.k7, f.k8, f.k9);
    }
    fprintf(c, "};\n\n");

    // Naive synth: [phoneme][register][formant] = (frequency, amplitude).
    fprintf(h, "extern const uint8_t naive_speech_phonemes[5][5][5][2];\n");
    fprintf(c, "const uint8_t naive_speech_phonemes[5][5][5][2] = {\n");
    for (int p = 0; p < 5; ++p) {
      fprintf(c, "  {\n");
      for (int r = 0; r < 5; ++r) {
        fprintf(c, "    {");
        for (int f = 0; f < 5; ++f) {
          const auto& fm = plaits::NaiveSpeechSynth::phonemes_[p][r].formant[f];
          fprintf(c, " { %d, %d },", fm.frequency, fm.amplitude);
        }
        fprintf(c, " },\n");
      }
      fprintf(c, "  },\n");
    }
    fprintf(c, "};\n\n");

    // SAM: [phoneme + guard][formant] = (frequency, amplitude index).
    fprintf(h, "extern const uint8_t sam_speech_phonemes[%d][3][2];\n", plaits::kSAMNumPhonemes + 1);
    fprintf(c, "const uint8_t sam_speech_phonemes[%d][3][2] = {\n", plaits::kSAMNumPhonemes + 1);
    for (int p = 0; p <= plaits::kSAMNumPhonemes; ++p) {
      fprintf(c, "  {");
      for (int f = 0; f < 3; ++f) {
        const auto& fm = plaits::SAMSpeechSynth::phonemes_[p].formant[f];
        fprintf(c, " { %d, %d },", fm.frequency, fm.amplitude);
      }
      fprintf(c, " },\n");
    }
    fprintf(c, "};\n\n");
    Table("sam_formant_amplitude_q31", "SAMSpeechSynth::formant_amplitude_lut", 31,
          plaits::SAMSpeechSynth::formant_amplitude_lut, 16);
    // lut_lpc_excitation_pulse (int8).
    fprintf(h, "extern const int8_t lut_lpc_excitation_pulse_i8[%d];\n", LUT_LPC_EXCITATION_PULSE_SIZE);
    fprintf(c, "const int8_t lut_lpc_excitation_pulse_i8[%d] = {", LUT_LPC_EXCITATION_PULSE_SIZE);
    for (int i = 0; i < LUT_LPC_EXCITATION_PULSE_SIZE; ++i) {
      fprintf(c, "%s%d,", (i % 16) ? " " : "\n  ", plaits::lut_lpc_excitation_pulse[i]);
    }
    fprintf(c, "\n};\n\n");
  }

  // log2(1 + i / 1024), Q30, for the OP-1 glue's increment -> note
  // conversion.
  {
    double v[1025];
    for (int i = 0; i <= 1024; ++i) v[i] = std::log2(1.0 + i / 1024.0);
    TableD("lut_log2_q30", "log2(1 + i / 1024)", 30, v, 1025);
  }

  // Reciprocal seeds: 1 / x at the middle of 64 buckets of [0.5, 1), Q30.
  {
    double v[64];
    for (int i = 0; i < 64; ++i) {
      double x = 0.5 + (i + 0.5) / 128.0;
      v[i] = 1.0 / x;
    }
    TableD("lut_reciprocal_seed_q30", "1 / x, x = 0.5 + (i + 0.5) / 128", 30, v, 64);
  }

  // 1 / sqrt(x) seeds over [0.25, 1): 48 buckets of width 1/64, Q30.
  {
    double v[48];
    for (int i = 0; i < 48; ++i) {
      double x = 0.25 + (i + 0.5) / 64.0;
      v[i] = 1.0 / std::sqrt(x);
    }
    TableD("lut_rsqrt_seed_q30", "1 / sqrt(x), x = 0.25 + (i + 0.5) / 64", 30, v, 48);
  }

  fprintf(h, "\n}  // namespace op1plaits\n\n#endif  // OP1PLAITS_FIXED_TABLES_H_\n");
  fprintf(c, "}  // namespace op1plaits\n");
  fclose(h);
  fclose(c);
  return 0;
}
