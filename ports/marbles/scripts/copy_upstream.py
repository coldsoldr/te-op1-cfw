#!/usr/bin/env python3
"""Copy Mutable Instruments Marbles' generator sources into ports/marbles/upstream.

The copy is mechanical: namespace marbles -> op1marbles, include paths
"marbles/..." -> "upstream/...", header guards MARBLES_ -> OP1MARBLES_UPSTREAM_.
Nothing else changes, so `--check` can undo the renames and compare every file
with upstream byte for byte. Marbles' preset scales live in settings.cc (which
pulls in the drivers); only the `preset_scales` table is extracted, into
upstream/scales.cc.

Usage (from ports/marbles):
    python3 scripts/copy_upstream.py [--mi ../../mutableinstruments] [--check]
"""
import argparse
import os
import re
import sys

FILES = [
    "random/discrete_distribution_quantizer.cc",
    "random/discrete_distribution_quantizer.h",
    "random/distributions.h",
    "random/lag_processor.cc",
    "random/lag_processor.h",
    "random/output_channel.cc",
    "random/output_channel.h",
    "random/quantizer.cc",
    "random/quantizer.h",
    "random/random_generator.h",
    "random/random_sequence.h",
    "random/random_stream.h",
    "random/t_generator.cc",
    "random/t_generator.h",
    "random/x_y_generator.cc",
    "random/x_y_generator.h",
    "ramp/ramp.h",
    "ramp/ramp_divider.h",
    "ramp/ramp_extractor.cc",
    "ramp/ramp_extractor.h",
    "ramp/ramp_generator.h",
    "ramp/slave_ramp.h",
    "resources.cc",
    "resources.h",
]

FORWARD = [
    (re.compile(r"namespace marbles\b"), "namespace op1marbles"),
    (re.compile(r"\bmarbles::"), "op1marbles::"),
    (re.compile(r'#include "marbles/'), '#include "upstream/'),
    (re.compile(r"\bMARBLES_"), "OP1MARBLES_UPSTREAM_"),
]
BACKWARD = [
    (re.compile(r"namespace op1marbles\b"), "namespace marbles"),
    (re.compile(r"\bop1marbles::"), "marbles::"),
    (re.compile(r'#include "upstream/'), '#include "marbles/'),
    (re.compile(r"\bOP1MARBLES_UPSTREAM_"), "MARBLES_"),
]

SCALES_HEADER = """// Marbles' preset scales, extracted from marbles/settings.cc (which also
// holds driver code) by scripts/copy_upstream.py. The table is unchanged.
"""


def apply(rules, text):
    for rx, rep in rules:
        text = rx.sub(rep, text)
    return text


def license_block(text):
    lines = text.splitlines(True)
    out = []
    for line in lines:
        if line.startswith("//"):
            out.append(line)
        else:
            break
    return "".join(out)


def extract_scales(settings_text):
    start = settings_text.index("const Scale preset_scales[6] = {")
    end = settings_text.index("};", start) + 2
    return settings_text[start:end]


def scales_files(mi):
    settings = open(os.path.join(mi, "marbles", "settings.cc"), newline="").read()
    lic = license_block(settings)
    table = extract_scales(settings)
    h = (lic + "//\n" + SCALES_HEADER + "\n"
         "#ifndef OP1MARBLES_UPSTREAM_SCALES_H_\n#define OP1MARBLES_UPSTREAM_SCALES_H_\n\n"
         '#include "upstream/random/quantizer.h"\n\n'
         "namespace op1marbles {\n\nextern const Scale preset_scales[6];\n\n"
         "}  // namespace op1marbles\n\n#endif  // OP1MARBLES_UPSTREAM_SCALES_H_\n")
    cc = (lic + "//\n" + SCALES_HEADER + "\n"
          '#include "upstream/scales.h"\n\nnamespace op1marbles {\n\n'
          + table + "\n\n}  // namespace op1marbles\n")
    return h, cc, table


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ap = argparse.ArgumentParser()
    ap.add_argument("--mi", default=os.path.join(here, "..", "..", "mutableinstruments"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    src_root = os.path.join(a.mi, "marbles")
    dst_root = os.path.join(here, "upstream")
    bad = 0
    for rel in FILES:
        src = os.path.join(src_root, rel)
        dst = os.path.join(dst_root, rel)
        text = open(src, newline="").read()
        if a.check:
            mine = open(dst, newline="").read()
            if apply(BACKWARD, mine) != text:
                print("DIFFERS from upstream after undoing the renames:", rel)
                bad += 1
            if mine != apply(FORWARD, text):
                print("DIFFERS from a fresh copy:", rel)
                bad += 1
        else:
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            with open(dst, "w", newline="") as f:
                f.write(apply(FORWARD, text))
    h, cc, table = scales_files(a.mi)
    # The bare initializer, for harnesses that build Scale tables in either
    # namespace (upstream's marbles:: or the copy's op1marbles::).
    inc = ("// Generated by scripts/copy_upstream.py from marbles/settings.cc.\n"
           + table[table.index("{"):table.rindex("}") + 1] + "\n")
    inc_path = os.path.join(dst_root, "scales_data.inc")
    if a.check:
        if open(inc_path, newline="").read() != inc:
            print("DIFFERS: scales_data.inc")
            bad += 1
    else:
        with open(inc_path, "w", newline="") as f:
            f.write(inc)
    if a.check:
        mine_cc = open(os.path.join(dst_root, "scales.cc"), newline="").read()
        if table not in mine_cc or mine_cc != cc:
            print("DIFFERS: scales.cc")
            bad += 1
        if open(os.path.join(dst_root, "scales.h"), newline="").read() != h:
            print("DIFFERS: scales.h")
            bad += 1
        print("copy-check (text): %d files, %d differences" % (len(FILES) + 2, bad))
        sys.exit(1 if bad else 0)
    with open(os.path.join(dst_root, "scales.h"), "w", newline="") as f:
        f.write(h)
    with open(os.path.join(dst_root, "scales.cc"), "w", newline="") as f:
        f.write(cc)
    print("copied %d files + scales.{h,cc} into %s" % (len(FILES), dst_root))


if __name__ == "__main__":
    main()
