#!/usr/bin/env python3
"""Generate src/tables_fx.cc: Marbles' float tables converted to fixed point.

Every value is converted from the exact value of the float in upstream's
resources.cc / settings.cc (as stored in single precision), so the port's
tables hold the same numbers the float code uses, to the precision of the
fixed-point format:

  dist_icdf_* (beta inverse CDFs)  Q31 uint32 (1.0 = 2^31), round to nearest
  lut_raised_cosine                Q31 uint32
  lut_logit                        threshold t = ceil(p * 2^32) - 1, so that
                                   for a Q32 uniform u: (u < p) == (u <= t)
  exp2 fraction table              Q30, 2^(i/256), i = 0..256
  preset scales                    degree voltages Q16 (round to nearest)

Usage: gen_tables.py MI_DIR OUT.cc
"""
import math
import os
import re
import struct
import sys
from fractions import Fraction


def f32(x):
    """Exact value of x rounded to float32, as a Fraction."""
    return Fraction(struct.unpack("<f", struct.pack("<f", float(x)))[0])


def rnd(fr):
    """Round half away from zero (values here are nonnegative)."""
    return int(math.floor(fr + Fraction(1, 2)))


def parse_float_arrays(text):
    arrays = {}
    for m in re.finditer(r"const float (\w+)\[\] = \{(.*?)\};", text, re.S):
        vals = [f32(v) for v in re.findall(r"[-+]?\d*\.\d+e[-+]\d+|[-+]?\d+\.\d*(?:e[-+]?\d+)?f?", m.group(2))]
        arrays[m.group(1)] = vals
    return arrays


def parse_pointer_table(text, name):
    m = re.search(r"const float\* %s\[\] = \{(.*?)\};" % name, text, re.S)
    return re.findall(r"\w+", m.group(1))


def parse_scales(settings_text):
    start = settings_text.index("const Scale preset_scales[6] = {")
    end = settings_text.index("};", start)
    body = settings_text[start:end]
    scales = []
    # Each scale: { base, n, { {v, w}, ... } }
    for sm in re.finditer(r"\{\s*([\d.]+)f,\s*(\d+),\s*\{(.*?)\}\s*\}", body, re.S):
        base = f32(sm.group(1))
        n = int(sm.group(2))
        degs = [(f32(v), int(w)) for v, w in re.findall(r"\{\s*([\d.]+)f,\s*(\d+)\s*\}", sm.group(3))]
        assert len(degs) == n, (n, degs)
        scales.append((base, degs))
    assert len(scales) == 6
    return scales


def q31(fr):
    v = rnd(fr * (1 << 31))
    assert 0 <= v <= (1 << 31), fr
    return v


def emit_u32_array(out, name, vals, per_line=6):
    out.append("const uint32_t %s[%d] = {" % (name, len(vals)))
    for i in range(0, len(vals), per_line):
        out.append("  " + " ".join("0x%08x," % v for v in vals[i:i + per_line]))
    out.append("};")


def main():
    mi, out_path = sys.argv[1], sys.argv[2]
    res = open(os.path.join(mi, "marbles", "resources.cc")).read()
    settings = open(os.path.join(mi, "marbles", "settings.cc")).read()
    arrays = parse_float_arrays(res)
    out = []
    out.append("// Generated by scripts/gen_tables.py from mutableinstruments/marbles")
    out.append("// resources.cc and settings.cc (MIT, (c) Emilie Gillet). Do not edit.")
    out.append("")
    out.append('#include "src/tables_fx.h"')
    out.append("")
    out.append("namespace op1marbles {")
    out.append("namespace fx {")
    out.append("")

    # Beta inverse CDFs.
    names = sorted(n for n in arrays if n.startswith("dist_icdf_"))
    for n in names:
        vals = arrays[n]
        assert len(vals) == 387, (n, len(vals))
        emit_u32_array(out, n, [q31(v) for v in vals])
    ptrs = parse_pointer_table(res, "distributions_table")
    assert len(ptrs) == 60, len(ptrs)
    out.append("const uint32_t* const distributions_table[%d] = {" % len(ptrs))
    for i in range(0, len(ptrs), 5):
        out.append("  " + " ".join("%s," % p for p in ptrs[i:i + 5]))
    out.append("};")

    rc = arrays["lut_raised_cosine"]
    assert len(rc) == 257
    emit_u32_array(out, "lut_raised_cosine", [q31(v) for v in rc])

    lg = arrays["lut_logit"]
    assert len(lg) == 257
    thr = []
    for p in lg:
        c = math.ceil(p * (1 << 32))
        assert 1 <= c <= (1 << 32) - 1
        thr.append(c - 1)
    emit_u32_array(out, "lut_logit_threshold", thr)

    exp2 = [rnd(Fraction(2 ** (i / 256.0)) * (1 << 30)) for i in range(257)]
    exp2[0] = 1 << 30
    exp2[256] = 1 << 31
    emit_u32_array(out, "lut_exp2_q30", exp2)

    # stmlib's SemitonesToRatio tables, as exact floats: value = m * 2^e with
    # a 24-bit mantissa m (the port multiplies them with float rounding
    # emulated, so the T clock frequency equals upstream's float exactly).
    units = open(os.path.join(mi, "stmlib", "dsp", "units.cc")).read()
    uarr = parse_float_arrays(units)
    for name in ("lut_pitch_ratio_high", "lut_pitch_ratio_low"):
        vals = uarr[name]
        assert len(vals) == 256, (name, len(vals))
        out.append("const Float24 %s[256] = {" % name)
        for v in vals:
            assert v > 0
            e = 0
            m = v
            while m >= (1 << 24):
                m /= 2
                e += 1
            while m < (1 << 23):
                m *= 2
                e -= 1
            assert m.denominator == 1, (name, v)
            out.append("  { %du, %d }," % (int(m), e))
        out.append("};")

    scales = parse_scales(settings)
    out.append("const ScaleFx preset_scales[6] = {")
    for base, degs in scales:
        out.append("  { %d, %d, {" % (rnd(base * 65536), len(degs)))
        for v, w in degs:
            out.append("    { %d, %d }," % (rnd(v * 65536), w))
        out.append("  } },")
    out.append("};")

    # Float constants used by the code, converted exactly.
    def const(name, fr, scale, comment):
        v = fr * scale
        assert v.denominator == 1, (name, v)
        out.append("// %s" % comment)
        out.append("const uint32_t %s = %du;" % (name, int(v)))
    out.append("")
    const("k005fQ32", f32(0.05), 1 << 32, "0.05f * 2^32 (exact)")
    const("k095fQ32", f32(0.95), 1 << 32, "0.95f * 2^32 (exact)")
    const("kMaxRampQ32", f32(0.9999), 1 << 32, "kMaxRampValue = 0.9999f, * 2^32 (exact)")
    const("k099999fQ32", f32(0.99999), 1 << 32, "0.99999f * 2^32 (exact; RampDivider's initial ratio)")
    out.append("")
    out.append("}  // namespace fx")
    out.append("}  // namespace op1marbles")
    with open(out_path, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", out_path)


if __name__ == "__main__":
    main()
