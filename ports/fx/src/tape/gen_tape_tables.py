"""Generates tape_tables.h (the TAPE effect's const tables).

Run from the repo root:  .venv/Scripts/python ports/fx/src/tape/gen_tape_tables.py
Plain Python (math only). The output is checked in; the firmware never runs this.

Tables:
  kTapeHalfband  the 2x polyphase IIR halfband's four allpass coefficients
                 (Q15), hiir's design (Laurent de Soras, WTFPL) for 4
                 coefficients and a transition band of 0.1 (of the 2x rate):
                 passband to 17.6 kHz, -70 dB stopband. c0, c2 are the even
                 path's, c1, c3 the odd path's.
  kTapeExp2      2^(i / 32) / 2 in Q15, i = 0..32 (the drive's mantissa).
  kTapeMakeup    33 points over the drive exponent e = -2 + 6 i / 32 (drive
                 g = 2^e / 2, 0.125 .. 8): the level compensation M (Q12),
                 so that a -12 dBFS sine keeps its RMS: M = rms(in) /
                 rms(S(g x)), S the quintic soft clip below.
  kTapeAgeK      33 points over the age knob: the HF loss's one-pole
                 coefficient (Q15), 1 - exp(-2 pi fc / 44100), fc = 20 kHz x
                 (2.2 kHz / 20 kHz)^a; the first point is 32767 (open).
  kTapeSine      sin(2 pi i / 256), i = 0..256, Q15 (the wobble LFOs).
  kTapeRecip     floor(65536 / n), n = 0..64 (0 for n = 0), for the ramps.

The saturation curve: S(v) = v - (2/3) v^3 + (1/5) v^5 for |v| <= 1, and
+-8/15 beyond (C2 at the knee: S'(1) = S''(1) = 0).
"""

import math
import os

FS = 44100.0
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tape_tables.h")


def hiir_coefs(nbr, transition):
    k = math.tan((1 - transition * 2) * math.pi / 4) ** 2
    kksqrt = (1 - k * k) ** 0.25
    e = 0.5 * (1 - kksqrt) / (1 + kksqrt)
    e4 = e ** 4
    q = e * (1 + e4 * (2 + e4 * (15 + 150 * e4)))
    order = nbr * 2 + 1
    out = []
    for index in range(nbr):
        c = index + 1
        i, j, num = 0, 1, 0.0
        while True:
            t = q ** (i * (i + 1)) * math.sin((i * 2 + 1) * c * math.pi / order) * j
            num += t
            j, i = -j, i + 1
            if abs(t) < 1e-100:
                break
        num *= q ** 0.25
        i, j, den = 1, -1, 0.0
        while True:
            t = q ** (i * i) * math.cos(i * 2 * c * math.pi / order) * j
            den += t
            j, i = -j, i + 1
            if abs(t) < 1e-100:
                break
        den += 0.5
        ww = num / den
        wwsq = ww * ww
        x = math.sqrt((1 - wwsq * k) * (1 - wwsq / k)) / (1 + wwsq)
        out.append((1 - x) / (1 + x))
    return out


def soft(v):
    if v >= 1:
        return 8.0 / 15.0
    if v <= -1:
        return -8.0 / 15.0
    return v - (2.0 / 3.0) * v ** 3 + 0.2 * v ** 5


def makeup(g, amp=0.25, points=4096):
    acc_in = acc_out = 0.0
    for i in range(points):
        x = amp * math.sin(2 * math.pi * (i + 0.5) / points)
        acc_in += x * x
        acc_out += soft(g * x) ** 2
    return math.sqrt(acc_in / acc_out)


def fmt(name, ctype, values, per_line=8):
    lines = ["const %s %s[%d] = {" % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    hb = [int(round(c * 32768)) for c in hiir_coefs(4, 0.1)]
    exp2 = [int(round(2 ** (i / 32.0) / 2 * 32768)) for i in range(33)]
    mk = []
    for i in range(33):
        e = -2 + 6.0 * i / 32
        g = 2 ** e / 2
        mk.append(int(round(makeup(g) * 4096)))
    age = []
    for i in range(33):
        a = i / 32.0
        fc = 20000.0 * (2200.0 / 20000.0) ** a
        k = 1 - math.exp(-2 * math.pi * fc / FS)
        age.append(32767 if i == 0 else int(round(k * 32768)))
    sine = [int(round(32767 * math.sin(2 * math.pi * i / 256))) for i in range(257)]
    recip = [0] + [65536 // n for n in range(1, 65)]

    body = [
        "// Generated by gen_tape_tables.py: do not edit.",
        "",
        "#ifndef OP1FX_SRC_TAPE_TAPE_TABLES_H_",
        "#define OP1FX_SRC_TAPE_TAPE_TABLES_H_",
        "",
        "#include <cstdint>",
        "",
        "namespace op1fx {",
        "",
        "// The halfband's allpass coefficients (Q15): c0, c1, c2, c3.",
        fmt("kTapeHalfband", "int16_t", hb),
        "// 2^(i / 32) / 2, Q15 (the last is 32768).",
        fmt("kTapeExp2", "int32_t", exp2),
        "// The makeup M over e = -2 + 6 i / 32, Q12.",
        fmt("kTapeMakeup", "int32_t", mk),
        "// The HF loss's one-pole coefficient over age, Q15.",
        fmt("kTapeAgeK", "int16_t", age),
        "// sin(2 pi i / 256), Q15.",
        fmt("kTapeSine", "int16_t", sine, 12),
        "// floor(65536 / n).",
        fmt("kTapeRecip", "int32_t", recip, 12),
        "",
        "}  // namespace op1fx",
        "",
        "#endif  // OP1FX_SRC_TAPE_TAPE_TABLES_H_",
        "",
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(body))
    print("wrote", OUT)
    print("halfband", hb)
    print("makeup", mk)
    print("age", age)


if __name__ == "__main__":
    main()
