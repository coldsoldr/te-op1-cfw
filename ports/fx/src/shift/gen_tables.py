# Writes shift_tables.h: SHIFT's constant tables, generated offline.
#   python gen_tables.py > shift_tables.h
# The Hilbert coefficients come from design_hilbert.py 4 40 16000 (the
# Q15 values it prints); the sine table is computed here.

import math

HILBERT = [4422, 13735, 22025, 27283, 30118, 31535, 32237, 32621]
SIN_SIZE = 512


def main():
    print("// Generated by gen_tables.py: do not edit.")
    print("#ifndef OP1FX_SRC_SHIFT_SHIFT_TABLES_H_")
    print("#define OP1FX_SRC_SHIFT_SHIFT_TABLES_H_")
    print()
    print("#include <cstdint>")
    print()
    print("namespace op1fx {")
    print()
    print("// The Hilbert pair's allpass coefficients a (Q15), in z^-2:")
    print("// y = a (x + y[n-2]) - x[n-2]. Even entries: the I path; odd: the Q")
    print("// path (which also has the z^-1). design_hilbert.py 4 40 16000.")
    print("const int16_t kShiftHilbert[8] = {")
    print("  " + ", ".join(str(v) for v in HILBERT) + ",")
    print("};")
    print()
    s = [int(round(32767 * math.sin(2 * math.pi * k / SIN_SIZE))) for k in range(SIN_SIZE)]
    c = [s[(k + SIN_SIZE // 4) % SIN_SIZE] for k in range(SIN_SIZE)]
    print("// The oscillator at phase 2 pi k / %d, k = 0..%d:" % (SIN_SIZE, SIN_SIZE - 1))
    print("//   [k]       sin | cos << 16     (x 32767, rounded)")
    print("//   [%d + k] the steps to entry k + 1, same packing (linear interpolation)" % SIN_SIZE)
    print("const uint32_t kShiftOsc[%d] = {" % (2 * SIN_SIZE))
    words = []
    def pack(lo, hi):
        return "0x%08xu" % (((hi & 0xffff) << 16) | (lo & 0xffff))
    for k in range(SIN_SIZE):
        words.append(pack(s[k], c[k]))
    for k in range(SIN_SIZE):
        n = (k + 1) % SIN_SIZE
        words.append(pack(s[n] - s[k], c[n] - c[k]))
    for i in range(0, len(words), 6):
        print("  " + ", ".join(words[i:i + 6]) + ",")
    print("};")
    print()
    print("}  // namespace op1fx")
    print()
    print("#endif  // OP1FX_SRC_SHIFT_SHIFT_TABLES_H_")


if __name__ == "__main__":
    main()
