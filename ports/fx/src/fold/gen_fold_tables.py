"""Generates fold_tables.h (the FOLD wavefolder's const tables).

Run from the repo root:  .venv/Scripts/python ports/fx/src/fold/gen_fold_tables.py
Plain Python (math only). The output is checked in; the firmware never runs this.

Tables:
  kFoldSin    256 segments of sin(2 pi p), p in turns: value | delta << 16 (Q15).
  kFoldSinc   1064 segments of sinc(pi d) = sin(pi d) / (pi d), d = 0..8.3 turns
              (d = u[n] - u[n-1], the ADAA step): value | delta << 16 (Q14,
              capped at 16383).
  kFoldGain   33 points over the fold knob: turns of sine phase per full-scale
              input, Q12: 0.25 x 16^k (0.25 .. 4 turns).
  kFoldLevel  33 points: the level compensation (Q15): wet RMS = dry RMS for a sine,
              averaged in dB over peaks of -9 .. -3 dBFS.
  kFoldTone   33 points over the tone knob: one-pole coefficient (Q15),
              1 - exp(-2 pi fc / 44100), fc = 300 Hz x 2^(7 k); the top is 32767
              (open).
  kFoldRecip  floor(65536 / n) for the ramps.
"""

import math
import os

FS = 44100.0
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fold_tables.h")


def packed(values):
    words = []
    for i in range(len(values) - 1):
        v = values[i]
        d = values[i + 1] - values[i]
        assert -32768 <= v <= 32767 and -32768 <= d <= 32767
        words.append(((d & 0xFFFF) << 16) | (v & 0xFFFF))
    return words


def sin_table():
    v = [int(round(32767 * math.sin(2 * math.pi * i / 256))) for i in range(257)]
    return packed(v)


def sinc(d):
    if d == 0:
        return 1.0
    return math.sin(math.pi * d) / (math.pi * d)


def sinc_table():
    # |u - u'| < 2^30 + 2^25 (|x G| <= 4 turns, |c| <= 1/8): segment <= 1056.
    v = [min(16383, int(round(16384 * sinc(j / 128.0)))) for j in range(1065)]
    return packed(v)


def gain_table():
    return [int(round(1024 * 16 ** (i / 32.0))) for i in range(33)]


def level_table(gains):
    # Averaged in dB over input peaks from -9 to -3 dBFS, so the curve is
    # smooth (one amplitude alone gives the Bessel ripple of J0).
    amps = [10 ** ((-9 + 0.75 * i) / 20) for i in range(9)]
    out = []
    steps = 2048
    for g in gains:
        turns = g / 4096.0
        db = 0.0
        for a in amps:
            acc = 0.0
            for k in range(steps):
                th = 2 * math.pi * (k + 0.5) / steps
                s = math.sin(2 * math.pi * turns * a * math.sin(th))
                acc += s * s
            rms = math.sqrt(acc / steps)
            db += 20 * math.log10((a / math.sqrt(2)) / rms)
        level = 10 ** (db / len(amps) / 20)
        out.append(min(32767, int(round(32768 * level))))
    return out


def tone_table():
    out = []
    for i in range(33):
        fc = 300.0 * 2 ** (7 * i / 32.0)
        k = 1 - math.exp(-2 * math.pi * fc / FS)
        out.append(min(32767, int(round(32768 * k))))
    out[32] = 32767
    return out


def recip_table():
    return [0] + [65536 // n for n in range(1, 65)]


def fmt(name, ctype, values, per_line, comment):
    lines = ["// " + comment, "const %s %s[%d] = {" % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        chunk = values[i:i + per_line]
        if ctype == "uint32_t":
            lines.append("  " + ", ".join("0x%08xu" % x for x in chunk) + ",")
        else:
            lines.append("  " + ", ".join(str(x) for x in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    gains = gain_table()
    parts = [
        "// Generated by gen_fold_tables.py: do not edit.",
        "",
        "#ifndef OP1FX_SRC_FOLD_FOLD_TABLES_H_",
        "#define OP1FX_SRC_FOLD_FOLD_TABLES_H_",
        "",
        "#include <cstdint>",
        "",
        "namespace op1fx {",
        "",
        fmt("kFoldSin", "uint32_t", sin_table(), 6,
            "sin(2 pi i / 256), Q15: value (low half) | delta to the next (high half)."),
        "",
        fmt("kFoldSinc", "uint32_t", sinc_table(), 6,
            "sinc(pi j / 128) (d = j / 128 turns), Q14 capped at 16383: value | delta << 16."),
        "",
        fmt("kFoldGain", "int32_t", gains, 11,
            "Fold knob (33 points) -> turns per full-scale input, Q12: 0.25 x 16^k."),
        "",
        fmt("kFoldLevel", "int32_t", level_table(gains), 11,
            "Fold knob (33 points) -> level compensation, Q15 (sine wet RMS = dry RMS, -9..-3 dBFS)."),
        "",
        fmt("kFoldTone", "int32_t", tone_table(), 11,
            "Tone knob (33 points) -> one-pole coefficient, Q15: fc = 300 Hz x 2^(7 k), top open."),
        "",
        fmt("kFoldRecip", "int32_t", recip_table(), 11,
            "floor(65536 / n), n = 0..64 (the per-sample ramps' steps)."),
        "",
        "}  // namespace op1fx",
        "",
        "#endif  // OP1FX_SRC_FOLD_FOLD_TABLES_H_",
        "",
    ]
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(parts))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
